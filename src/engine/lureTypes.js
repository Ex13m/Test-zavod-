export function guessLureType(fileName = '') {
  const n = fileName.toLowerCase()
  const map = [
    // товары
    [/крюч|hook|офсет|offset|тройник|treble/, 'hooks'],
    [/удочк|удилищ|спиннинг|rod|палк|бланк/, 'rod'],
    [/катушк|reel|шпул/, 'reel'],
    [/шнур|леск|line|braid|плетен|флюр|fluoro/, 'line'],
    [/джерси|jersey|футболк|худи|hoodie|кепк|одежд|shirt/, 'apparel'],
    [/нож|knife|филей|fillet/, 'knife'],
    // приманки
    [/вобл|wobb|minnow|crank|shad/, 'wobbler'],
    [/верт|spin(?!ner)|mepps|aglia/, 'spinner'],
    [/колеб|spoon|ложк/, 'spoon'],
    [/силик|soft|твистер|виброхв|worm|twister|gum/, 'soft'],
    [/джиг|jig|головк/, 'jig'],
    [/поппер|popp|topwater/, 'popper'],
    [/баланс|balan|ice/, 'balancer'],
    [/спиннерб|bait/, 'spinnerbait'],
  ]
  for (const [re, id] of map) if (re.test(n)) return id
  return 'wobbler'
}
