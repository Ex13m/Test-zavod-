export const LURE_TYPE_LIST = Object.values(LURE_TYPES)

export function guessLureType(fileName = '') {
  const n = fileName.toLowerCase()
  const map = [
    [/вобл|wobb|minnow|crank|shad/, 'wobbler'],
    [/верт|spin(?!ner)|mepps|aglia/, 'spinner'],
    [/колеб|spoon|ложк/, 'spoon'],
    [/силик|soft|твистер|виброхв|worm|twister/, 'soft'],
    [/джиг|jig|головк/, 'jig'],
    [/поппер|popp|topwater/, 'popper'],
    [/баланс|balan|ice/, 'balancer'],
    [/спиннерб|bait/, 'spinnerbait'],
  ]
  for (const [re, id] of map) if (re.test(n)) return id
  return 'wobbler'
}
